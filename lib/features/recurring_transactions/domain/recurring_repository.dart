import '../../../core/database/app_database.dart';

class RecurringWithDetails {
  final RecurringTransaction recurring;
  final Account? sourceAccount;
  final Account? destinationAccount;
  final Category? category;

  RecurringWithDetails({
    required this.recurring,
    this.sourceAccount,
    this.destinationAccount,
    this.category,
  });

  bool get isDue => recurring.isActive && DateTime.now().isAfter(recurring.nextDueDate);
}

abstract class RecurringRepository {
  Stream<List<RecurringWithDetails>> watchRecurring();
  Future<void> createRecurring({
    required String title,
    required String type,
    required int amountCents,
    String? sourceAccountId,
    String? destinationAccountId,
    String? categoryId,
    required String frequency,
    required DateTime startDate,
    required DateTime nextDueDate,
    DateTime? endDate,
    bool isAutoGenerated = false,
  });
  Future<void> toggleActive(String id, bool active);
  Future<void> processDueRecurring();
  Future<void> deleteRecurring(String id);
}
