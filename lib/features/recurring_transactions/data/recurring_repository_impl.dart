import 'package:drift/drift.dart';
import 'package:uuid/uuid.dart';
import '../../../core/constants/app_constants.dart';
import '../../../core/database/app_database.dart';
import '../../transactions/domain/transaction_repository.dart';
import '../domain/recurring_repository.dart';

class RecurringRepositoryImpl implements RecurringRepository {
  final AppDatabase _db;
  final TransactionRepository _transactionRepository;
  final _uuid = const Uuid();

  RecurringRepositoryImpl(this._db, this._transactionRepository);

  @override
  Stream<List<RecurringWithDetails>> watchRecurring() {
    return _db.select(_db.recurringTransactions).watch().asyncMap((items) async {
      final List<RecurringWithDetails> result = [];

      for (final rec in items) {
        Account? srcAcc;
        Account? destAcc;
        Category? cat;

        if (rec.sourceAccountId != null) {
          srcAcc = await (_db.select(_db.accounts)..where((tbl) => tbl.id.equals(rec.sourceAccountId!))).getSingleOrNull();
        }
        if (rec.destinationAccountId != null) {
          destAcc = await (_db.select(_db.accounts)..where((tbl) => tbl.id.equals(rec.destinationAccountId!))).getSingleOrNull();
        }
        if (rec.categoryId != null) {
          cat = await (_db.select(_db.categories)..where((tbl) => tbl.id.equals(rec.categoryId!))).getSingleOrNull();
        }

        result.add(RecurringWithDetails(
          recurring: rec,
          sourceAccount: srcAcc,
          destinationAccount: destAcc,
          category: cat,
        ));
      }

      return result;
    });
  }

  @override
  Future<void> createRecurring({
    required String title,
    required String type,
    required int amountCents,
    String? sourceAccountId,
    String? destinationAccountId,
    String? categoryId,
    required String frequency,
    required DateTime startDate,
    required DateTime nextDueDate,
    DateTime? endDate,
    bool isAutoGenerated = false,
  }) async {
    final now = DateTime.now();
    await _db.into(_db.recurringTransactions).insert(
      RecurringTransactionsCompanion.insert(
        id: _uuid.v4(),
        title: title,
        type: type,
        amount: amountCents,
        sourceAccountId: Value(sourceAccountId),
        destinationAccountId: Value(destinationAccountId),
        categoryId: Value(categoryId),
        frequency: frequency,
        startDate: startDate,
        nextDueDate: nextDueDate,
        endDate: Value(endDate),
        isAutoGenerated: Value(isAutoGenerated),
        isActive: const Value(true),
        createdAt: now,
        updatedAt: now,
      ),
    );
  }

  @override
  Future<void> toggleActive(String id, bool active) async {
    final now = DateTime.now();
    await (_db.update(_db.recurringTransactions)..where((tbl) => tbl.id.equals(id))).write(
      RecurringTransactionsCompanion(
        isActive: Value(active),
        updatedAt: Value(now),
      ),
    );
  }

  @override
  Future<void> processDueRecurring() async {
    final now = DateTime.now();
    final dueItems = await (_db.select(_db.recurringTransactions)
          ..where((tbl) =>
              tbl.isActive.equals(true) &
              tbl.nextDueDate.isSmallerOrEqualValue(now)))
        .get();

    for (final item in dueItems) {
      if (item.isAutoGenerated) {
        // Automatically create transaction
        if (item.type == TransactionType.income.name &&
            item.destinationAccountId != null &&
            item.categoryId != null) {
          await _transactionRepository.createIncome(
            amountCents: item.amount,
            destinationAccountId: item.destinationAccountId!,
            categoryId: item.categoryId!,
            transactionDate: now,
            description: '[Recurring] ${item.title}',
            isRecurring: true,
          );
        } else if (item.type == TransactionType.expense.name &&
            item.sourceAccountId != null &&
            item.categoryId != null) {
          await _transactionRepository.createExpense(
            amountCents: item.amount,
            sourceAccountId: item.sourceAccountId!,
            categoryId: item.categoryId!,
            transactionDate: now,
            description: '[Recurring] ${item.title}',
            isRecurring: true,
          );
        } else if (item.type == TransactionType.transfer.name &&
            item.sourceAccountId != null &&
            item.destinationAccountId != null) {
          await _transactionRepository.createTransfer(
            amountCents: item.amount,
            sourceAccountId: item.sourceAccountId!,
            destinationAccountId: item.destinationAccountId!,
            transactionDate: now,
            description: '[Recurring] ${item.title}',
          );
        }
      }

      // Calculate next due date
      final next = _calculateNextDueDate(item.nextDueDate, item.frequency);
      await (_db.update(_db.recurringTransactions)..where((tbl) => tbl.id.equals(item.id))).write(
        RecurringTransactionsCompanion(
          nextDueDate: Value(next),
          updatedAt: Value(now),
        ),
      );
    }
  }

  DateTime _calculateNextDueDate(DateTime current, String frequency) {
    if (frequency == RecurrenceFrequency.daily.name) {
      return current.add(const Duration(days: 1));
    } else if (frequency == RecurrenceFrequency.weekly.name) {
      return current.add(const Duration(days: 7));
    } else if (frequency == RecurrenceFrequency.monthly.name) {
      return DateTime(current.year, current.month + 1, current.day);
    } else if (frequency == RecurrenceFrequency.yearly.name) {
      return DateTime(current.year + 1, current.month, current.day);
    }
    return current.add(const Duration(days: 30));
  }

  @override
  Future<void> deleteRecurring(String id) async {
    await (_db.delete(_db.recurringTransactions)..where((tbl) => tbl.id.equals(id))).go();
  }
}
